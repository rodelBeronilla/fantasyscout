"""The columns the export ships to the pages, as TypeScript unions (#479).

    uv run python -m export.ts_columns          # write web/src/generated/columns.ts
    uv run python -m export.ts_columns --check  # exit 1 when the file is stale

``export/layout.py`` names the columns of the board and streamers files and of the player file's
sections. The pages declare row types over them; ``ExportedRow`` in the generated file fails the
web type check when a row type names a field the export does not ship, so a renamed column breaks
``npm run check`` instead of a page reading undefined at runtime. ``tests/test_ts_columns.py``
holds the committed file to this module's output.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from export import layout

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "web" / "src" / "generated" / "columns.ts"

UNIONS = (
    ("BoardColumn", "BOARD_COLUMNS", "the board file, board/<league>.json"),
    ("StreamerColumn", "STREAMER_COLUMNS", "the streamers file, streamers/<league>.json"),
    ("PlayerBoardColumn", "PLAYER_BOARD_COLUMNS", "the player file's board section"),
    ("PlayerRollingColumn", "PLAYER_ROLLING_COLUMNS", "the player file's rolling section"),
    ("PlayerZscoreColumn", "PLAYER_ZSCORE_COLUMNS", "the player file's z-score section"),
)


def render() -> str:
    lines = [
        "// Generated by `uv run python -m export.ts_columns` from export/layout.py. Do not edit.",
        "",
    ]
    for name, attr, what in UNIONS:
        columns = getattr(layout, attr)
        lines.append(f"/** The columns of {what} ({attr}). */")
        lines.append(f"export type {name} =")
        lines.extend(f"  | '{c}'" for c in columns)
        lines[-1] += ";"
        lines.append("")
    lines += [
        "/** The fields a type names, without an index signature (`[key: string]: unknown`). */",
        "type NamedKeys<T> = keyof {",
        "  [K in keyof T as string extends K ? never : number extends K ? never : K]: T[K];",
        "};",
        "",
        "/**",
        " * `Fields` itself, when every field it names is one of `Columns`. A field the",
        " * export does not ship fails the type check at the type's declaration, naming",
        " * the field (its type must be never). An index signature, for columns read by a",
        " * computed name, is left alone.",
        " */",
        "export type ExportedRow<",
        "  Columns extends string,",
        "  Fields extends Record<Exclude<NamedKeys<Fields>, Columns>, never>,",
        "> = Fields;",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the file is stale")
    args = parser.parse_args(argv)
    text = render()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
    if args.check:
        if current != text:
            print(
                f"{OUT.relative_to(ROOT)} is stale; run `uv run python -m export.ts_columns`",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT.relative_to(ROOT)} is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
